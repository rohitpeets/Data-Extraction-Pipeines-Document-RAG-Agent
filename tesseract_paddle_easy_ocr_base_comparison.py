def paddleocr_to_words(texts, scores, polys):
    words = []
    for text, score, poly in zip(texts, scores, polys):
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        words.append({
            "text": text,
            "conf": score,
            "left": min(xs),
            "top": min(ys),
            "width": max(xs) - min(xs),
            "height": max(ys) - min(ys),
        })
    return words

