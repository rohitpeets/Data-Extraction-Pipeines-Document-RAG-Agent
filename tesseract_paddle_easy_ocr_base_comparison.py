def reconstruct_lines(words):
    if not words:
        return []
    heights = [w["height"] for w in words]
    row_tolerance = max(10, int(sorted(heights)[len(heights)//2] * 0.6))

    words_sorted = sorted(words, key=lambda w: w["top"])
    lines = []
    current_line = [words_sorted[0]]
    for w in words_sorted[1:]:
        if abs(w["top"] - current_line[-1]["top"]) <= row_tolerance:
            current_line.append(w)
        else:
            lines.append(current_line)
            current_line = [w]
    lines.append(current_line)

    readable_lines = []
    for line in lines:
        line_sorted = sorted(line, key=lambda w: w["left"])
        readable_lines.append(" ".join(w["text"] for w in line_sorted))
    return readable_lines

